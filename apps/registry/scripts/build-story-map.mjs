#!/usr/bin/env node
/**
 * Map every registry item to its Storybook story ids.
 *
 * The component pages embed `storybook.interlace.tools/iframe.html?id=<id>` to
 * show a LIVE render instead of a screenshot or a link. That render is the one
 * already asserted by the storybook a11y gate, so the preview can't drift from
 * what CI verified — and it costs the registry app zero bundle weight.
 *
 * The map is derived from the story sources in this repo, not fetched from the
 * deployed Storybook: a build must not depend on another deployment being up.
 * That independence is the reason this file has to REPLICATE Storybook's id
 * algorithm rather than read it, and replicating it wrong is silent — a wrong
 * id renders an empty frame, not an error. See `storyId` below.
 *
 * Output: `public/data/story-map.json`, regenerated by build-registry.mjs and
 * drift-checked by `build-registry.mjs --check`.
 */

import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const REGISTRY_ROOT = path.resolve(SCRIPT_DIR, '..');
const REPO_ROOT = path.resolve(REGISTRY_ROOT, '..', '..');
const STORIES_DIR = path.join(REPO_ROOT, 'apps/storybook/src/stories');
const OUT_FILE = path.join(REGISTRY_ROOT, 'public/data/story-map.json');

/* ─── Storybook's story-id algorithm ──────────────────────────────────────
 *
 * `toId(title, storyNameFromExport(exportName))`, ported.
 *
 * The export name is NOT sanitized directly. Storybook runs it through
 * lodash `startCase` FIRST, which splits it into words — so `WithoutImage`
 * becomes "Without Image" and only then `without-image`. Sanitizing the raw
 * export gave `withoutimage`, an id no story has ever had.
 *
 * That single missing step is invisible for one-word exports (`Default`,
 * `Dark`, `Loading`), which is every id this map used to be spot-checked on,
 * and wrong for every multi-word one: 210 of the 705 ids in the generated map
 * pointed at nothing, and the frames for them rendered blank on the live site.
 *
 * `assertParityWithStorybook` below re-derives every id with Storybook's own
 * implementation whenever that package resolves, so a future upstream change
 * to the algorithm is reported instead of silently blanking previews. The
 * local port stays the source of truth either way: generated output must not
 * depend on whether a devDependency happens to be installed.
 */

/**
 * lodash `words`, restricted to the ASCII shapes an export name can have.
 * `Grid36` → `['Grid', '36']`, `CTASection` → `['CTA', 'Section']`,
 * `RTL` → `['RTL']`.
 */
const WORDS_RE = /[A-Z]{2,}(?=[A-Z][a-z]|\b)|[A-Z]?[a-z]+|[A-Z]+|[0-9]+/g;

/** Storybook's `sanitize` — lowercase, non-alphanumerics collapsed to `-`. */
const sanitize = (s) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');

/** Storybook's `storyNameFromExport` — lodash `startCase` on the export name. */
const storyNameFromExport = (exportName) =>
  (exportName.match(WORDS_RE) ?? [exportName]).join(' ');

const storyId = (title, exportName) =>
  `${sanitize(title)}--${sanitize(storyNameFromExport(exportName))}`;

/* ─── Source extraction ───────────────────────────────────────────────── */

/**
 * The `title` of the default-exported `meta`, NOT the first `title:` in the
 * file.
 *
 * Story files carry fixture data, and article fixtures have titles too:
 * `PrevNextPost.stories.tsx` opens with `{ title: 'The ESLint rule quality
 * bar' }` twelve lines above `title: 'Blocks/PrevNextPost'`. An unanchored
 * `title:` match took the fixture, so every id for three components was
 * derived from a blog-post headline.
 */
const metaTitle = (source) => {
  const decl = source.search(/^(?:export\s+)?const\s+meta\b/m);
  if (decl === -1) return null;
  return source.slice(decl).match(/^\s*title:\s*['"]([^'"]+)['"]/m)?.[1] ?? null;
};

/**
 * Every exported story, with the slice of source that defines it.
 *
 * `StoryObj` as well as `Story`: a story typed against a secondary component
 * (`StoryObj<typeof RankedBarList>`) is still a story, and matching only
 * `Story\b` dropped all five of Meter's `Ranked*` exports — the component's
 * entire second half was missing from its own page.
 */
const STORY_EXPORT_RE = /^export\s+const\s+(\w+)\s*:\s*Story(?:Obj)?\b/gm;

const storyBlocks = (source) => {
  const heads = [...source.matchAll(STORY_EXPORT_RE)].map((m) => ({
    name: m[1],
    at: m.index,
  }));
  return heads.map((head, i) => ({
    name: head.name,
    body: source.slice(head.at, heads[i + 1]?.at ?? source.length),
  }));
};

/**
 * The value of a TOP-LEVEL property of the story object.
 *
 * Depth-aware rather than indentation-aware, because both spellings are in
 * use and an indentation anchor only understands one of them:
 *
 *   export const Dark: Story = { ...Default, globals: { theme: 'dark' } };
 *   export const Dark: Story = {
 *     globals: { theme: 'dark' },
 *   };
 *
 * Anchoring on two-space indent read 79 dark stories where there are 102 —
 * every one-liner was invisible. Depth also keeps `args.article.tags` (an
 * ArticleCard fixture) from being mistaken for the story's own `tags`.
 */
const topLevelValue = (block, key) => {
  const start = block.indexOf('{', block.indexOf('='));
  if (start === -1) return null;
  // Depth per character, with string bodies masked out.
  const depth = new Array(block.length).fill(-1);
  let d = 0;
  let quote = null;
  let esc = false;
  let end = block.length;
  for (let i = start; i < block.length; i++) {
    const c = block[i];
    if (esc) {
      esc = false;
      continue;
    }
    if (quote) {
      if (c === '\\') esc = true;
      else if (c === quote) quote = null;
      continue;
    }
    // Comments, skipped before quotes: a prose apostrophe in `// the registry's
    // thumbnail` opened a string that swallowed the next 40 lines, and every
    // property after it read as nested. Silent — the property just went
    // missing.
    if (c === '/' && block[i + 1] === '/') {
      i = block.indexOf('\n', i);
      if (i === -1) break;
      continue;
    }
    if (c === '/' && block[i + 1] === '*') {
      const close = block.indexOf('*/', i + 2);
      if (close === -1) break;
      i = close + 1;
      continue;
    }
    if (c === '"' || c === "'" || c === '`') {
      quote = c;
      continue;
    }
    if (c === '{' || c === '[' || c === '(') d++;
    else if (c === '}' || c === ']' || c === ')') {
      d--;
      if (d === 0) {
        end = i;
        break;
      }
    } else depth[i] = d;
  }
  const re = new RegExp(`\\b${key}\\s*:`, 'g');
  for (const m of block.slice(0, end).matchAll(re)) {
    if (depth[m.index] === 1) return block.slice(m.index + m[0].length, end);
  }
  return null;
};

/** `tags: ['preview']` declared on the story itself. */
const tagsOf = (block) => {
  const rest = topLevelValue(block, 'tags');
  const list = rest?.match(/^\s*\[([^\]]*)\]/)?.[1];
  return list ? [...list.matchAll(/['"]([^'"]+)['"]/g)].map((m) => m[1]) : [];
};

/**
 * Does this story render in the dark scheme?
 *
 * Read from `globals: { theme: 'dark' }` — the mechanism, not the name. Until
 * this changed, dark was inferred from an export being CALLED `Dark`, which
 * meant `StatGroup.DarkMode` (a real dark story) was invisible to the map
 * while a story called `Dark` that had lost its globals would still have been
 * advertised as the dark preview. That second case is not hypothetical: it is
 * exactly the defect that made every dark preview on the site render light.
 */
const isDark = (block) => {
  const rest = topLevelValue(block, 'globals');
  return /^\s*\{[^}]*\btheme:\s*['"]dark['"]/.test(rest ?? '');
};

/* ─── Preview selection policy ────────────────────────────────────────────
 *
 * The preview is the component's thumbnail — for most visitors it is the only
 * render of it they will ever look at. Picking `Default` unconditionally made
 * that thumbnail a 92×22px sparkline and a lone 40×36px toggle square inside a
 * 280px-tall frame: technically the component, practically a speck.
 *
 * So the choice is authored, not inferred, and it is authored in the story
 * file next to the story it names:
 *
 *   1. the story tagged `preview`      — an explicit "show THIS one"
 *   2. else the first of `default`, `basic`, `overview`, `variants`
 *   3. else the first story in the file
 *
 * A tag rather than a list in this script: a list here is a second place to
 * remember, and it rots the moment a story is renamed — the tag moves with the
 * story, and it is visible in the Storybook sidebar and index as well.
 *
 * `previewDark` is the SAME story in the dark scheme, matched by export name
 * (`InContext` → `InContextDark`), so toggling the site's scheme repaints the
 * preview instead of swapping it for a different composition. Falling back to
 * any dark story keeps the coverage components had before this rule existed.
 */
const PREVIEW_TAG = 'preview';
const DEFAULT_PREFERENCE = ['Default', 'Basic', 'Overview', 'Variants'];
/** The story that demonstrates the skeleton / loading placeholder. */
const SKELETON_TAG = 'preview-loading';
const SKELETON_PREFERENCE = [
  'Loading',
  'Skeleton',
  'LoadingState',
  'PageSkeleton',
];

const byName = (stories, names) => {
  for (const want of names) {
    const hit = stories.find((s) => s.name === want);
    if (hit) return hit;
  }
  return null;
};

const byTag = (stories, tag) => stories.find((s) => s.tags.includes(tag)) ?? null;

const pickPreview = (stories) =>
  byTag(stories, PREVIEW_TAG) ??
  byName(stories, DEFAULT_PREFERENCE) ??
  stories[0] ??
  null;

const pickPreviewDark = (stories, preview) => {
  const dark = stories.filter((s) => s.dark);
  if (dark.length === 0) return null;
  return (
    (preview && dark.find((s) => s.name === `${preview.name}Dark`)) ??
    dark.find((s) => s.name === 'Dark') ??
    dark[0]
  );
};

const pickSkeleton = (stories) =>
  byTag(stories, SKELETON_TAG) ??
  byName(stories, SKELETON_PREFERENCE) ??
  // Any story whose name ends in `Skeleton` (`ArticleCardSkeleton`) or
  // `Loading` (`RankedLoading`) — the shape-matched placeholder is the point,
  // not the export name someone happened to choose for it.
  stories.find((s) => /(?:Skeleton|Loading)$/.test(s.name)) ??
  null;

/* ─── Registry key ────────────────────────────────────────────────────── */

/**
 * A story titled `Primitives/GradeBadge` belongs to the registry item
 * `grade-badge`; match on the filename, which already carries the component's
 * PascalCase name, converted to the registry's kebab-case. Two passes so
 * acronym runs split correctly: `CTASection` → `cta-section`, not
 * `ct-a-section`.
 */
const keyForFile = (file) =>
  path
    .basename(file, '.stories.tsx')
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Z]+)([A-Z][a-z])/g, '$1-$2')
    .toLowerCase();

/**
 * Which entry wins when two files reduce to the same key.
 *
 * `foundations/typography.stories.tsx` and `primitives/Typography.stories.tsx`
 * both key to `typography`, and the loser was decided by directory sort order
 * — silently, and only correctly by luck. The registry item `typography` is
 * the primitive, so component tiers outrank the reference-page tiers.
 */
const TIER_RANK = [
  'Primitives',
  'Blocks',
  'Charts',
  'Templates',
  'Pages',
  'Fumadocs',
  'MagicUI',
  'Foundations',
  'Tokens',
];
const tierRank = (title) => {
  const i = TIER_RANK.indexOf(title.split('/')[0]);
  return i === -1 ? TIER_RANK.length : i;
};

const walk = async (dir) => {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    /*
     * no-zip-slip flags any `path.join(dir, <name>)` — but these names come
     * from `readdir` on a repo-local directory, not from an archive, and the
     * containment assertion below is the check the rule asks for.
     */
    // eslint-disable-next-line node-security/no-zip-slip
    const full = path.join(dir, entry.name);
    if (!full.startsWith(STORIES_DIR + path.sep)) continue;
    if (entry.isDirectory()) out.push(...(await walk(full)));
    else if (entry.name.endsWith('.stories.tsx')) out.push(full);
  }
  return out;
};

export const buildStoryMap = async () => {
  const files = (await walk(STORIES_DIR)).sort();
  /** @type {Record<string, any>} */
  const map = {};
  const collisions = [];
  /** Every (title, export name) → id derivation, for the parity check. */
  const pairs = [];

  for (const file of files) {
    const source = await readFile(file, 'utf8');
    const title = metaTitle(source);
    if (!title) continue;

    const stories = storyBlocks(source).map(({ name, body }) => ({
      name,
      id: storyId(title, name),
      tags: tagsOf(body),
      dark: isDark(body),
    }));
    if (stories.length === 0) continue;
    for (const s of stories) pairs.push({ title, name: s.name, id: s.id });

    const preview = pickPreview(stories);
    const previewDark = pickPreviewDark(stories, preview);
    const skeleton = pickSkeleton(stories);

    const key = keyForFile(file);
    const entry = {
      title,
      storyIds: stories.map((s) => s.id),
      preview: preview?.id ?? null,
      previewDark: previewDark?.id ?? null,
      skeleton: skeleton?.id ?? null,
    };

    const held = map[key];
    if (held) {
      collisions.push(`${key}: ${held.title} vs ${title}`);
      if (tierRank(held.title) <= tierRank(title)) continue;
    }
    map[key] = entry;
  }

  // Deterministic key order regardless of directory traversal.
  const sorted = {};
  for (const key of Object.keys(map).sort()) sorted[key] = map[key];
  return { map: sorted, collisions, pairs };
};

/**
 * Re-derive every id with Storybook's OWN implementation and report any
 * disagreement.
 *
 * Never changes the output — the generated file must be identical on a machine
 * that has `storybook` installed and one that does not — it only makes a drift
 * in the ported algorithm loud instead of silent.
 */
export const assertParityWithStorybook = async (pairs) => {
  let csf;
  try {
    csf = await import('storybook/internal/csf');
  } catch {
    return null; // not installed here; the port stands on its own
  }
  const mismatches = [];
  for (const { title, name, id } of pairs) {
    const theirs = csf.toId(title, csf.storyNameFromExport(name));
    if (theirs !== id) mismatches.push(`${title}.${name}: ${id} vs ${theirs}`);
  }
  return mismatches;
};

const main = async () => {
  const { map, collisions, pairs } = await buildStoryMap();
  await mkdir(path.dirname(OUT_FILE), { recursive: true });
  await writeFile(OUT_FILE, JSON.stringify(map, null, 2) + '\n', 'utf8');

  const entries = Object.values(map);
  const total = entries.reduce((n, e) => n + e.storyIds.length, 0);
  const withDark = entries.filter((e) => e.previewDark).length;
  const withSkeleton = entries.filter((e) => e.skeleton).length;
  const tagged = entries.filter(
    (e) => e.preview && !e.preview.endsWith('--default'),
  ).length;
  console.log(
    `build-story-map: ${entries.length} components, ${total} stories, ` +
      `${withDark} with a dark preview, ${withSkeleton} with a skeleton story, ` +
      `${tagged} previewing a non-default story → ${path.relative(REPO_ROOT, OUT_FILE)}`,
  );

  for (const c of collisions) {
    console.warn(`build-story-map: key collision — ${c} (kept the higher tier)`);
  }
  const mismatches = await assertParityWithStorybook(pairs);
  if (mismatches?.length) {
    console.warn(
      `build-story-map: ${mismatches.length} id(s) disagree with Storybook's own toId() — ` +
        `the ported algorithm has drifted:\n  ` +
        mismatches.slice(0, 20).join('\n  '),
    );
  }
};

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main().catch((err) => {
    console.error(err);
    process.exit(1);
  });
}
