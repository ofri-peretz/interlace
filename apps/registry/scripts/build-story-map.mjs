#!/usr/bin/env node
/**
 * Map every registry item to its Storybook story ids.
 *
 * The component pages embed `storybook.interlace.tools/iframe.html?id=<id>` to
 * show a LIVE render instead of a screenshot or a link. That render is the one
 * already asserted by the storybook a11y gate, so the preview can't drift from
 * what CI verified — and it costs the registry app zero bundle weight.
 *
 * The map is derived from the story sources in this repo, not fetched from the
 * deployed Storybook: a build must not depend on another deployment being up.
 *
 * Story id algorithm (matches Storybook's): the `title` and the export name are
 * each lowercased with every non-alphanumeric run collapsed to `-`, joined by
 * `--`. `Primitives/GradeBadge` + `Default` → `primitives-gradebadge--default`.
 *
 * Output: `public/data/story-map.json`, regenerated by build-registry.mjs.
 */

import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const REGISTRY_ROOT = path.resolve(SCRIPT_DIR, '..');
const REPO_ROOT = path.resolve(REGISTRY_ROOT, '..', '..');
const STORIES_DIR = path.join(REPO_ROOT, 'apps/storybook/src/stories');
const OUT_FILE = path.join(REGISTRY_ROOT, 'public/data/story-map.json');

const TITLE_RE = /^\s*title:\s*['"]([^'"]+)['"]/m;
const STORY_EXPORT_RE = /^export\s+const\s+(\w+)\s*:\s*Story\b/gm;

/** Storybook's `sanitize` — lowercase, non-alphanumerics collapsed to `-`. */
const sanitize = (s) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');

/** The story whose export name best represents "just show me the component". */
const DEFAULT_PREFERENCE = ['default', 'basic', 'overview', 'variants'];
/** The story that demonstrates the skeleton / loading placeholder. */
const SKELETON_PREFERENCE = ['loading', 'skeleton', 'loading-state'];
/**
 * Dark-theme twin of the default story.
 *
 * The obvious approach — `?globals=theme:dark` on the default story — does
 * NOT work against the deployed Storybook (verified: the story still renders
 * light), so the site swaps to the story that already carries the `withDark`
 * decorator. 87 of 100 components have one; the rest fall back to the light
 * render.
 */
const DARK_PREFERENCE = ['dark'];

const walk = async (dir) => {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    /*
     * no-zip-slip flags any `path.join(dir, <name>)` — but these names come
     * from `readdir` on a repo-local directory, not from an archive, and the
     * containment assertion below is the check the rule asks for.
     */
    // eslint-disable-next-line node-security/no-zip-slip
    const full = path.join(dir, entry.name);
    if (!full.startsWith(STORIES_DIR + path.sep)) continue;
    if (entry.isDirectory()) out.push(...(await walk(full)));
    else if (entry.name.endsWith('.stories.tsx')) out.push(full);
  }
  return out;
};

const pick = (ids, preference) => {
  for (const want of preference) {
    const hit = ids.find((id) => id.endsWith(`--${want}`));
    if (hit) return hit;
  }
  return null;
};

export const buildStoryMap = async () => {
  const files = (await walk(STORIES_DIR)).sort();
  /** @type {Record<string, {title: string, storyIds: string[], preview: string|null, skeleton: string|null}>} */
  const map = {};

  for (const file of files) {
    const source = await readFile(file, 'utf8');
    const title = source.match(TITLE_RE)?.[1];
    if (!title) continue;

    const prefix = sanitize(title);
    const storyIds = [
      ...source.matchAll(STORY_EXPORT_RE),
    ].map(([, name]) => `${prefix}--${sanitize(name)}`);
    if (storyIds.length === 0) continue;

    // A story titled `Primitives/GradeBadge` belongs to the registry item
    // `grade-badge`; match on the filename, which already carries the
    // component's PascalCase name, converted to the registry's kebab-case.
    // Two passes so acronym runs split correctly: `CTASection` → `cta-section`,
    // not `ct-a-section`.
    const key = path
      .basename(file, '.stories.tsx')
      .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
      .replace(/([A-Z]+)([A-Z][a-z])/g, '$1-$2')
      .toLowerCase();

    map[key] = {
      title,
      storyIds,
      preview: pick(storyIds, DEFAULT_PREFERENCE) ?? storyIds[0],
      previewDark: pick(storyIds, DARK_PREFERENCE),
      skeleton: pick(storyIds, SKELETON_PREFERENCE),
    };
  }

  return map;
};

const main = async () => {
  const map = await buildStoryMap();
  await mkdir(path.dirname(OUT_FILE), { recursive: true });
  await writeFile(OUT_FILE, JSON.stringify(map, null, 2) + '\n', 'utf8');
  const withSkeleton = Object.values(map).filter((m) => m.skeleton).length;
  console.log(
    `build-story-map: ${Object.keys(map).length} components, ${withSkeleton} with a skeleton story → ${path.relative(REPO_ROOT, OUT_FILE)}`,
  );
};

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main().catch((err) => {
    console.error(err);
    process.exit(1);
  });
}
