#!/usr/bin/env node
/**
 * Project the design tokens into `src/tokens.generated.ts`, the palette React Native reads.
 *
 * DERIVED, not forked. The colours are written once, in `packages/ui/styles/brand/*.css`.
 * `apps/registry/scripts/build-tokens.mjs` turns them into the DTCG file
 * `apps/registry/public/tokens/interlace.tokens.json` (with an sRGB hex beside every oklch
 * value), and this script reads that file. React Native paints sRGB and does not parse
 * `oklch()`, so the hex is the value native gets: the same pixel the browser paints.
 *
 * `--check` fails when the committed file differs from what the JSON gives, so the web and the
 * native palettes cannot drift apart. The test script runs it.
 *
 * Only the semantic colours a native component reads are projected. The house-brand decoration
 * (hero sky, window controls, the thread strands, the brand mark) stays web-only.
 */

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const PACKAGE_ROOT = path.resolve(HERE, '..');
const REPO_ROOT = path.resolve(PACKAGE_ROOT, '..', '..');
const SOURCE = path.join(REPO_ROOT, 'apps/registry/public/tokens/interlace.tokens.json');
const OUT_FILE = path.join(PACKAGE_ROOT, 'src/tokens.generated.ts');
const CHECK_ONLY = process.argv.includes('--check');

/** The colour tokens native components read, in the order the CSS declares them. */
export const NATIVE_COLOR_TOKENS = [
  'primary',
  'primary-hover',
  'primary-active',
  'primary-foreground',
  'primary-subtle',
  'primary-subtle-foreground',
  'background',
  'foreground',
  'card',
  'card-foreground',
  'popover',
  'popover-foreground',
  'muted',
  'muted-foreground',
  'border',
  'input',
  'ring',
  'accent',
  'accent-foreground',
  'secondary',
  'secondary-foreground',
  'destructive',
  'destructive-foreground',
  'success',
  'success-foreground',
  'warning',
  'warning-foreground',
  'info',
  'info-foreground',
  'caution',
  'caution-foreground',
  'highlight',
  'highlight-foreground',
  'scrim',
  'scrim-foreground',
  'chart-1',
  'chart-2',
  'chart-3',
  'chart-4',
  'chart-5',
  'viz-grid',
  'viz-axis',
  'viz-edge',
];

const camel = (name) => name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

const fail = (message) => {
  throw new Error(`native build-tokens: ${message}`);
};

/** A token's sRGB hex, following `{theme.scheme.name}` aliases. */
function hexOf(tokens, theme, scheme, name, seen = new Set()) {
  const key = `${theme}.${scheme}.${name}`;
  if (seen.has(key)) fail(`alias cycle at ${key}`);
  seen.add(key);
  const token = tokens[theme]?.[scheme]?.[name];
  if (!token) fail(`${key} is missing from ${path.relative(REPO_ROOT, SOURCE)}`);
  if (token.$type !== 'color') fail(`${key} is a ${token.$type}, not a color`);
  const value = token.$value;
  if (typeof value === 'string') {
    const ref = /^\{(\w[\w-]*)\.(light|dark)\.([\w-]+)\}$/.exec(value);
    if (!ref) fail(`${key} has an alias this script cannot follow: ${value}`);
    return hexOf(tokens, ref[1], ref[2], ref[3], seen);
  }
  if (!/^#[0-9a-f]{6}([0-9a-f]{2})?$/i.test(value?.hex ?? '')) fail(`${key} has no sRGB hex`);
  return value.hex.toLowerCase();
}

function radiusOf(tokens, theme) {
  const token = tokens[theme]?.light?.radius;
  if (token?.$type !== 'dimension' || token.$value.unit !== 'rem') fail(`${theme} radius is not in rem`);
  return token.$value.value * 16;
}

export function render(tokens) {
  const themes = Object.keys(tokens).filter((k) => !k.startsWith('$'));
  const lines = [
    '// GENERATED by scripts/build-tokens.mjs from apps/registry/public/tokens/interlace.tokens.json,',
    '// which is generated from packages/ui/styles/brand/*.css. Do not edit: change the CSS and run',
    '// `node apps/registry/scripts/build-tokens.mjs`, then `npm run tokens -w @interlace/native`.',
    '',
    '/** Every colour a native component reads, camelCased from its `--interlace-*` CSS name. */',
    'export const COLOR_TOKENS = [',
    ...NATIVE_COLOR_TOKENS.map((n) => `  '${camel(n)}',`),
    '] as const;',
    '',
    'export type ColorToken = (typeof COLOR_TOKENS)[number];',
    '',
    '/** One full palette: a hex for every colour token. */',
    'export type Palette = Record<ColorToken, string>;',
    '',
    '/** The registered themes, each in both schemes, as sRGB hex. `radius` is the base corner in points. */',
    'export const THEME_PALETTES = {',
  ];
  for (const theme of themes) {
    lines.push(`  '${theme}': {`);
    lines.push(`    radius: ${radiusOf(tokens, theme)},`);
    for (const scheme of ['light', 'dark']) {
      lines.push(`    ${scheme}: {`);
      for (const name of NATIVE_COLOR_TOKENS) {
        lines.push(`      ${camel(name)}: '${hexOf(tokens, theme, scheme, name)}',`);
      }
      lines.push('    },');
    }
    lines.push('  },');
  }
  lines.push('} as const satisfies Record<string, { radius: number; light: Palette; dark: Palette }>;');
  lines.push('');
  lines.push('export type NativeThemeName = keyof typeof THEME_PALETTES;');
  lines.push('');
  return lines.join('\n');
}

async function main() {
  const tokens = JSON.parse(await readFile(SOURCE, 'utf8'));
  const next = render(tokens);
  const current = await readFile(OUT_FILE, 'utf8').catch(() => '');
  if (CHECK_ONLY) {
    if (current !== next) {
      console.error(
        'native build-tokens: src/tokens.generated.ts is stale. Run `npm run tokens -w @interlace/native`.',
      );
      process.exit(1);
    }
    console.log('native build-tokens: src/tokens.generated.ts matches the token file.');
    return;
  }
  if (current !== next) await writeFile(OUT_FILE, next);
  console.log(`native build-tokens: wrote ${path.relative(REPO_ROOT, OUT_FILE)}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
